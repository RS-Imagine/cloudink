import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
import { build, transform } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('.', import.meta.url);
await build({
  entryPoints: [new URL('ui/app.js', root).pathname],
  outfile: new URL('ui/app.generated.js', root).pathname,
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify: true,
  external: ['/blog_wasm.js', '/image-maintenance.js', '/home-illustration.js'],
});
await build({
  entryPoints: [new URL('ui/preview.worker.js', root).pathname],
  outfile: new URL('ui/preview.worker.generated.js', root).pathname,
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify: true,
  external: ['/blog_wasm.js'],
});
await build({
  entryPoints: [new URL('ui/image.worker.js', root).pathname],
  outfile: new URL('ui/image.worker.generated.js', root).pathname,
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify: true,
});
await build({
  entryPoints: [new URL('ui/image-maintenance.js', root).pathname],
  outfile: new URL('ui/image-maintenance.generated.js', root).pathname,
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify: true,
});
await build({
  entryPoints: [new URL('ui/home-illustration.js', root).pathname],
  outfile: new URL('ui/home-illustration.generated.js', root).pathname,
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify: true,
});
const paths = [
  ['/home-illustration.js', 'ui/home-illustration.generated.js', 'text/javascript; charset=utf-8'],
  ['/editorial-botanical.svg', '../assets/editorial-botanical.svg', 'image/svg+xml'],
  ['/image-maintenance.js', 'ui/image-maintenance.generated.js', 'text/javascript; charset=utf-8'],
  ['/image.worker.js', 'ui/image.worker.generated.js', 'text/javascript; charset=utf-8'],
  ['/admin-theme.js', '../assets/theme.js', 'text/javascript; charset=utf-8'],
  ['/', 'ui/index.html', 'text/html; charset=utf-8'],
  ['/favicon.svg', '../assets/cloudink.svg', 'image/svg+xml'],
  ['/style.css', 'ui/style.css', 'text/css; charset=utf-8'],
  ['/app.js', 'ui/app.generated.js', 'text/javascript; charset=utf-8'],
  ['/preview.worker.js', 'ui/preview.worker.generated.js', 'text/javascript; charset=utf-8'],
  ['/blog_wasm.js', 'ui/wasm/blog_wasm.js', 'text/javascript; charset=utf-8'],
  ['/blog_wasm_bg.wasm', 'ui/wasm/blog_wasm_bg.wasm', 'application/wasm'],
];
const assets = {};
for (const [path, file, type] of paths) {
  let bytes = await readFile(new URL(file, root));
  if (path === '/style.css') {
    const sources = [
      '../assets/design-tokens.css',
      'ui/style.css',
      '../assets/design-foundation.css',
      '../assets/motion.css',
      'ui/studio.css',
      'ui/workflows.css',
      '../assets/mobile.css',
      '../assets/expressive.css',
    ];
    const stylesheets = await Promise.all(
      sources.map(async (file) => {
        const source = await readFile(new URL(file, root), 'utf8');
        if (file === '../assets/design-tokens.css' || file === '../assets/design-foundation.css')
          return source;
        return (
          await transform(source, {
            loader: 'css',
            minify: true,
            target: 'es2022',
          })
        ).code;
      }),
    );
    bytes = Buffer.from(stylesheets.join('\n'));
    for (let index = 0; index < sources.length; index++)
      console.log(JSON.stringify({ stylesheet: sources[index], gzip: gzipSync(stylesheets[index]).length }));
    console.log(JSON.stringify({ adminStylesheetGzip: gzipSync(bytes).length }));
  }
  assets[path] = {
    type,
    data: bytes.toString('base64'),
    etag: '\"' + createHash('sha256').update(bytes).digest('hex') + '\"',
  };
}
await writeFile(
  new URL('src/assets.generated.ts', root),
  '// Generated by build-ui.mjs. Do not edit.\nexport const ASSETS: Record<string,{type:string;data:string;etag:string}> = ' +
    JSON.stringify(assets) +
    ';\n',
);
console.log('Bundled editor and Rust preview assets.');
