pub fn build(root: &Path, worker_assets: &Path, bundler: &Bundler) -> Result<()> {
    for (name, external) in JS_ENTRIES {
        let entry = format!("ui/{name}.js");
        let output = root.join(format!("cloud-admin/ui/{name}.generated.js"));
        bundler.js(
            "cloud-admin",
            Source::File(&entry),
            &output,
            "esm",
            external,
        )?;
    }
    bundler.js(
        "cloud-admin",
        Source::Inline {
            body: "export { default } from 'highlight.js/lib/common';",
            name: "preview-highlight.js",
        },
        &root.join("cloud-admin/ui/preview-highlight.generated.js"),
        "esm",
        &[],
    )?;
    let mut table = String::from(
        "// Generated by cargo xtask build. Do not edit.\n\
         const ASSETS: &[(&str, Asset)] = &[\n",
    );
    for (index, (route, file, mime)) in ASSETS.iter().enumerate() {
        let bytes = match *route {
            "/" => cache_busted_shell(&fs::read_to_string(root.join(file))?)?.into_bytes(),
            "/style.css" => stylesheet(root, bundler)?.into_bytes(),
            _ => fs::read(root.join(file))?,
        };
        let filename = format!("asset-{index}");
        let etag = format!("\"{}\"", sha256(&bytes));
        fs::write(worker_assets.join(&filename), bytes)?;
        writeln!(
            table,
            "    ({route:?}, Asset {{ bytes: include_bytes!({filename:?}), mime: {mime:?}, etag: {etag:?} }}),"
        )?;
    }
    table.push_str("];\n");
    fs::write(worker_assets.join("assets.rs"), table)?;
    println!("Bundled editor and Rust preview assets.");
    Ok(())
}

pub fn restore_generated(root: &Path, worker_assets: &Path) -> Result<()> {
    for (index, (_, file, _)) in ASSETS.iter().enumerate() {
        let cached = worker_assets.join(format!("asset-{index}"));
        ensure!(cached.is_file(), "cache is missing {file}");
        if file.ends_with(".generated.js") || file.starts_with("cloud-admin/ui/wasm/") {
            let target = root.join(file);
            if let Some(parent) = target.parent() {
                fs::create_dir_all(parent)?;
            }
            fs::copy(cached, target)?;
        }
    }
    Ok(())
}

pub fn write_versions(root: &Path, path: &Path) -> Result<()> {
    let response = response_version(root)?;
    let generation = generation_version(root)?;
    fs::write(
        path,
        format!(
            "pub const RESPONSE_VERSION: &str = {response:?};\n\
             pub const GENERATION_VERSION: &str = {generation:?};\n"
        ),
    )?;
    Ok(())
}

fn cache_busted_shell(html: &str) -> Result<String> {
    let mut timestamp = SystemTime::now().duration_since(UNIX_EPOCH)?.as_millis();
    let mut digits = Vec::new();
    loop {
        let digit = (timestamp % 36) as u32;
        digits.push(char::from_digit(digit, 36).expect("base-36 digit"));
        timestamp /= 36;
        if timestamp == 0 {
            break;
        }
    }
    let version = digits.into_iter().rev().collect::<String>();
    Ok(html
        .replacen(
            "href=\"/style.css\"",
            &format!("href=\"/style.css?v={version}\""),
            1,
        )
        .replacen(
            "src=\"/app.js\"",
            &format!("src=\"/app.js?v={version}\""),
            1,
        ))
}

fn stylesheet(root: &Path, bundler: &Bundler) -> Result<String> {
    let mut styles = Vec::new();
    for (file, minify) in STYLES {
        let source = fs::read_to_string(root.join(file))?;
        let style = if *minify {
            bundler.css(&source, "es2022")?
        } else {
            source
        };
        let relative = file
            .strip_prefix("cloud-admin/")
            .map_or_else(|| format!("../{file}"), str::to_owned);
        println!(
            "{}",
            json!({ "stylesheet": relative, "gzip": gzip_size(style.as_bytes())? })
        );
        styles.push(style);
    }
    let output = styles.join("\n");
    println!(
        "{}",
        json!({ "adminStylesheetGzip": gzip_size(output.as_bytes())? })
    );
    Ok(output)
}

fn response_version(root: &Path) -> Result<String> {
    let source = root.join("crates/worker/src");
    let mut files = fs::read_dir(&source)?.collect::<std::io::Result<Vec<_>>>()?;
    files.sort_by_key(|entry| entry.file_name());
    let mut digest = Sha256::new();
    for file in files {
        if file.path().extension().is_some_and(|ext| ext == "rs") {
            let name = file.file_name();
            let name = name.to_string_lossy();
            digest.update(format!("../crates/worker/src/{name}"));
            digest.update(fs::read(file.path())?);
        }
    }
    for file in ["crates/worker/Cargo.toml", "crates/worker/Cargo.lock"] {
        digest.update(format!("../{file}"));
        digest.update(fs::read(root.join(file))?);
    }
    Ok(hex(&digest.finalize()))
}

fn generation_version(root: &Path) -> Result<String> {
    let mut digest = Sha256::new();
    for name in [
        "page_rendering.rs",
        "html_rewriter.rs",
        "image.rs",
        "image_header.rs",
        "media.rs",
    ] {
        let path = format!("crates/worker/src/{name}");
        digest.update(format!("../{path}"));
        digest.update(fs::read(root.join(path))?);
    }
    Ok(hex(&digest.finalize()))
}
